"""Convert a Maia (lc0 SE-resnet) .pb.gz into the compact policy-only file the app loads.

usage: python3 tools/convert_maia.py maia-1900.pb.gz policy_map.h policy_index.py out.bin out-tables.js

Batch norm is folded into the convs the same way lc0 does (network_legacy.cc), the value
head is dropped, and weights are stored as float16 in this order:
  input conv, then per block: conv1, conv2, se.w1, se.b1, se.w2, se.b2, then policy1, policy.
"""
import gzip, re, struct, sys
import numpy as np

def decode(buf):
    """Minimal protobuf wire decoder: field number -> list of raw values."""
    out, i = {}, 0
    while i < len(buf):
        key, i = varint(buf, i)
        field, wt = key >> 3, key & 7
        if wt == 0:
            v, i = varint(buf, i)
        elif wt == 1:
            v, i = buf[i:i + 8], i + 8
        elif wt == 2:
            n, i = varint(buf, i)
            v, i = buf[i:i + n], i + n
        elif wt == 5:
            v, i = buf[i:i + 4], i + 4
        else:
            raise ValueError(f'wire type {wt}')
        out.setdefault(field, []).append(v)
    return out

def varint(buf, i):
    r = s = 0
    while True:
        b = buf[i]; i += 1
        r |= (b & 0x7F) << s; s += 7
        if b < 0x80:
            return r, i

def layer(msg):
    if msg is None:
        return np.zeros(0, np.float32)
    d = decode(msg)
    if 3 not in d:
        return np.zeros(0, np.float32)
    enc = d.get(4, [1])[0]
    if enc not in (0, 1):  # UNKNOWN/LINEAR16 only — Maia uses LINEAR16
        raise ValueError(f'unsupported encoding {enc}')
    lo = struct.unpack('<f', d[1][0])[0]
    hi = struct.unpack('<f', d[2][0])[0]
    raw = np.frombuffer(d[3][0], dtype='<u2').astype(np.float64)
    return (lo + (hi - lo) * raw / 65535.0).astype(np.float32)

def sub(d, f):
    return d.get(f, [None])[0]

def conv_block(msg):
    d = decode(msg)
    w, b = layer(sub(d, 1)), layer(sub(d, 2))
    means, var = layer(sub(d, 3)), layer(sub(d, 4))
    gammas, betas = layer(sub(d, 5)), layer(sub(d, 6))
    outs = len(b) or len(means)
    if not len(b):
        b = np.zeros(outs, np.float32)
    if len(means):
        if not len(betas):
            betas, gammas = np.zeros(outs, np.float32), np.ones(outs, np.float32)
        g = gammas / np.sqrt(var + 1e-5)
        w = (w.reshape(outs, -1) * g[:, None]).reshape(-1)
        b = -g * (means - b) + betas
    return w.astype(np.float32), b.astype(np.float32), outs

def main(src, map_h, index_py, out_bin, out_js):
    net = decode(gzip.open(src).read())
    w = decode(net[10][0])
    parts = []
    iw, ib, ch = conv_block(w[1][0])
    parts += [iw, ib]
    blocks = w.get(2, [])
    for r in blocks:
        rd = decode(r)
        for f in (1, 2):
            cw, cb, _ = conv_block(rd[f][0])
            parts += [cw, cb]
        se = decode(rd[3][0])
        parts += [layer(sub(se, k)) for k in (1, 2, 3, 4)]
    se_ch = len(layer(sub(decode(decode(blocks[0])[3][0]), 2)))
    p1w, p1b, _ = conv_block(w[11][0])
    pw, pb, pouts = conv_block(w[3][0])
    parts += [p1w, p1b, pw, pb]
    flat = np.concatenate(parts).astype(np.float16)
    open(out_bin, 'wb').write(flat.tobytes())

    table = re.search(r'kConvPolicyMap\[\] = \{(.*?)\};', open(map_h).read(), re.S).group(1)
    conv_map = [int(x) for x in re.findall(r'-?\d+', table)]
    moves = re.findall(r'"([a-h][1-8][a-h][1-8][qrbn]?)"', open(index_py).read())
    # lc0 only reads the first 73 policy planes (kPolicyUsedPlanes); the rest are padding
    assert len(moves) == 1858 and len(conv_map) == 73 * 64 and pouts >= 73, (len(moves), len(conv_map), pouts)
    with open(out_js, 'w') as f:
        f.write('// generated by tools/convert_maia.py — lc0 policy tables (GPL-3.0, LeelaChessZero)\n')
        f.write(f'export const SHAPE = {{ filters: {ch}, blocks: {len(blocks)}, se: {se_ch}, policyPlanes: {pouts} }};\n')
        f.write('export const MOVES = "' + ' '.join(moves) + '".split(" ");\n')
        f.write('export const CONV_MAP = new Int16Array([' + ','.join(map(str, conv_map)) + ']);\n')
    print(f'{len(flat)} weights -> {out_bin} ({len(flat) * 2 / 1e6:.2f} MB); filters={ch} blocks={len(blocks)} se={se_ch} policy planes={pouts}')

if __name__ == '__main__':
    main(*sys.argv[1:])
